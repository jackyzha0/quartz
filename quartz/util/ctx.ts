import { QuartzConfig } from "../cfg"
import { ProcessedContent, QuartzPluginData } from "../plugins/vfile"
import { FileTrieNode } from "./fileTrie"
import type { ContentDetails } from "../plugins/types"
import { FilePath, FullSlug, slugifyFilePath } from "./path"

export interface Argv {
  directory: string
  verbose: boolean
  output: string
  serve: boolean
  watch: boolean
  port: number
  wsPort: number
  remoteDevHost?: string
  concurrency?: number
}

export type BuildTimeTrieData = QuartzPluginData & {
  slug: string
  title: string
  filePath: string
}

/**
 * Mapping from logical asset names (e.g. "index.css") to their content-hashed
 * filenames (e.g. "index-a3f2c1b.css"). Populated by the ComponentResources
 * emitter before pages are rendered.
 */
export type HashedResourceNames = Record<string, string>

export interface BuildCtx {
  buildId: string
  argv: Argv
  cfg: QuartzConfig
  allSlugs: FullSlug[]
  allFiles: FilePath[]
  /**
   * Frontmatter permalinks: content file (relative path) → the slug it is published at
   * (Obsidian Publish semantics, see util/permalinks.ts). Plain data, so it reaches worker threads.
   */
  permalinks?: Record<string, FullSlug>
  trie?: FileTrieNode<BuildTimeTrieData>
  incremental: boolean
  /** Virtual pages generated by page type plugins (e.g. tag pages, folder pages, bases pages) */
  virtualPages: ProcessedContent[]
  /** Content-hashed asset filenames, populated by ComponentResources emitter */
  hashedResourceNames?: HashedResourceNames
  /** Maps CSS content strings to their emitted hashed filenames. Populated by ComponentResources. */
  componentCssMap?: Map<string, string>
  /** Maps inline CSS/JS content to extracted external file paths. Populated by ComponentResources. */
  extractedInlineResources?: Map<string, string>
  /**
   * The site's content index (one entry per published page, virtual pages included), exactly as
   * written to `static/contentIndex.json` plus `date` / `description`. Built once per build,
   * before the emit phase that runs plugin emitters — so every emitter except ComponentResources
   * and PageTypeDispatcher can reuse it instead of rebuilding it. Read-only: emitters run in
   * parallel and share it.
   */
  contentIndex?: ReadonlyMap<FullSlug, Readonly<ContentDetails>>
}

export function trieFromAllFiles(allFiles: QuartzPluginData[]): FileTrieNode<BuildTimeTrieData> {
  const trie = new FileTrieNode<BuildTimeTrieData>([])
  allFiles.forEach((file) => {
    if (file.frontmatter) {
      trie.add(
        {
          ...file,
          slug: file.slug!,
          title: file.frontmatter.title,
          filePath: file.filePath!,
        },
        // placed by file path (permalinked notes stay in their folder), linked by slug
        file.relativePath ? slugifyFilePath(file.relativePath) : file.slug!,
      )
    }
  })

  return trie
}

export type WorkerSerializableBuildCtx = Omit<BuildCtx, "cfg" | "trie">
